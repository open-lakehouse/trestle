//! The Python client workspace's files (see [`Plan::python_client`]): a uv project under
//! `client/`, beside the client environments every target writes.
//!
//! Target-neutral and pure: a deploy target appends [`python_client_files`] to its
//! [`MaterializedOutput`](crate::MaterializedOutput). The workspace reads its endpoints from
//! `client/host.env` at runtime (marimo's `dotenv` setting), so nothing here depends on the
//! target's addressing.

use std::fmt::Write as _;

use crate::plan::{Plan, PythonWorkspace};
use crate::render::output::OutputFile;

/// The workspace's directory, relative to the environment root.
pub const PYTHON_CLIENT_DIR: &str = "client";

/// The base notebook every workspace gets: checks the client environment loads and the gateway
/// answers.
const CONNECT_NOTEBOOK: &str = include_str!("../../templates/client/00_connect.py");
const CONNECT_NOTEBOOK_FILE: &str = "00_connect.py";

/// The files of `plan`'s Python client workspace; empty when the selection didn't ask for one.
///
/// `pyproject.toml`, the README and `.gitignore` are regenerated on every render (trestle owns
/// them). Notebooks are seeded once and then left alone (`preserve`), so a user's edits
/// survive a re-render.
pub fn python_client_files(plan: &Plan) -> Vec<OutputFile> {
    let Some(workspace) = &plan.python_client else {
        return Vec::new();
    };
    let generated = |name: &str, contents: String| OutputFile {
        path: format!("{PYTHON_CLIENT_DIR}/{name}"),
        contents,
        sensitive: false,
        preserve: false,
        moved_from: None,
    };
    let notebook = |file: &str, contents: &str| OutputFile {
        path: format!("{PYTHON_CLIENT_DIR}/notebooks/{file}"),
        contents: contents.to_string(),
        sensitive: false,
        preserve: true,
        moved_from: None,
    };

    let mut files = vec![
        generated(
            "pyproject.toml",
            render_pyproject(&plan.env_name, workspace),
        ),
        generated("README.md", render_readme(workspace)),
        generated(
            ".gitignore",
            ".venv/\n__marimo__/\n__pycache__/\nmlruns/\n".into(),
        ),
        notebook(CONNECT_NOTEBOOK_FILE, CONNECT_NOTEBOOK),
    ];
    files.extend(
        workspace
            .notebooks
            .iter()
            .map(|(_, n)| notebook(&n.file, &n.contents)),
    );
    files
}

/// `pyproject.toml` for a uv-managed, non-packaged project whose marimo runtime loads
/// `host.env`.
fn render_pyproject(env_name: &str, workspace: &PythonWorkspace) -> String {
    let mut out = String::from(
        "# Generated by `trestle env`; re-render to update. Your own packages go in a separate\n\
         # project or `uv add --script` (this file is rewritten when the stack changes).\n",
    );
    let _ = writeln!(out, "[project]");
    let _ = writeln!(out, "name = {}", toml_str(&format!("{env_name}-client")));
    let _ = writeln!(out, "version = \"0.1.0\"");
    let _ = writeln!(
        out,
        "description = {}",
        toml_str(&format!(
            "Client notebooks for the `{env_name}` environment"
        ))
    );
    let _ = writeln!(out, "requires-python = \">=3.11\"");
    let _ = writeln!(out, "dependencies = [");
    for dep in &workspace.dependencies {
        let _ = writeln!(out, "    {},", toml_str(dep));
    }
    let _ = writeln!(out, "]");
    out.push_str(
        "\n[tool.uv]\n\
         package = false\n\
         \n\
         # Notebooks reach the stack through the generated client environment. Paths resolve\n\
         # against this file's directory; swap in `container.env` to run inside the network.\n\
         [tool.marimo.runtime]\n\
         dotenv = [\"host.env\"]\n",
    );
    out
}

/// The workspace README: how to run it, and what each notebook shows.
fn render_readme(workspace: &PythonWorkspace) -> String {
    let mut out = String::from(include_str!("../../templates/client/README.md"));
    out.push_str("\n## Notebooks\n\n");
    let _ = writeln!(
        out,
        "- `notebooks/{CONNECT_NOTEBOOK_FILE}`: checks the client environment and the gateway."
    );
    for (module, notebook) in &workspace.notebooks {
        let _ = writeln!(
            out,
            "- `notebooks/{}` ({module}): {}",
            notebook.file, notebook.title
        );
    }
    if workspace.notebooks.is_empty() {
        out.push_str(
            "\nRe-create the environment with `--client-examples` (or set\n\
             `selection.client.examples = true` in `env.toml` and re-render) to add example\n\
             notebooks for the selected services.\n",
        );
    }
    out
}

/// `s` as a TOML basic string, quoted and escaped.
fn toml_str(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{PlanCtx, Selection, baseline_catalog};

    fn plan(selection: Selection) -> Plan {
        baseline_catalog()
            .plan(&selection, &PlanCtx::default())
            .unwrap()
    }

    #[test]
    fn no_workspace_unless_selected() {
        let p = plan(Selection::modules(["envoy", "postgres", "mlflow"]));
        assert!(p.python_client.is_none());
        assert!(python_client_files(&p).is_empty());
    }

    #[test]
    fn pyproject_is_valid_toml_with_the_base_dependencies() {
        let mut selection = Selection::modules(["envoy"]);
        selection.client.python = true;
        let p = plan(selection);
        let files = python_client_files(&p);
        let pyproject = &files
            .iter()
            .find(|f| f.path == "client/pyproject.toml")
            .unwrap()
            .contents;
        let parsed: toml::Table = pyproject.parse().unwrap();
        let deps: Vec<&str> = parsed["project"]["dependencies"]
            .as_array()
            .unwrap()
            .iter()
            .map(|d| d.as_str().unwrap())
            .collect();
        assert_eq!(deps, crate::PYTHON_CLIENT_BASE_DEPENDENCIES);
        assert_eq!(
            parsed["tool"]["marimo"]["runtime"]["dotenv"]
                .as_array()
                .unwrap()[0]
                .as_str(),
            Some("host.env")
        );
    }
}
