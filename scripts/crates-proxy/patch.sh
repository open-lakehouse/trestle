#!/usr/bin/env bash
# Patch an upstream's crates from its local checkout, so builds work while the
# crates.io proxy still hides a fresh release (see docs/crates-proxy.md).
#
# Writes a marked block of `patch.crates-io.<crate> = { path = ... }` entries to the
# consumer's gitignored .cargo/config.toml. Each upstream gets its own block, so
# patching trestle and mangrove side by side works; other config is kept.
#
# Usage:
#   patch.sh <repo> [crate...]    # default: every published <repo> crate the locks use
#   patch.sh --remove <repo>      # drop the <repo> block again
#
# Before committing, run lock-registry.sh: a lock resolved under the patch has
# lost the crates' registry source/checksum lines, and CI (--locked) rejects it.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$here/lib.sh"

remove=0
if [[ "${1:-}" == "--remove" ]]; then
    remove=1
    shift
fi
repo="${1:?usage: patch.sh [--remove] <repo> [crate...]}"
shift

consumer="$(consumer_root)"
config="$consumer/.cargo/config.toml"
marker="# >>> crates-proxy:$repo"
end="# <<< crates-proxy:$repo"

mkdir -p "$consumer/.cargo"
touch "$config"
git -C "$consumer" check-ignore -q .cargo/config.toml ||
    echo "warning: .cargo/config.toml is not gitignored in $consumer; never commit a [patch]" >&2

# Files written by the per-repo configure-trestle-deps.sh predecessors use a
# [patch.crates-io] table, which can't coexist with the dotted keys below.
if grep -q '^# Generated by dev/scripts/configure-trestle-deps.sh' "$config"; then
    : >"$config"
fi

# The config without this upstream's previous block (and without leading blank lines).
rest="$(awk -v b="$marker" -v e="$end" 'index($0, b) == 1 {skip = 1} !skip {print} $0 == e {skip = 0}' "$config" |
    sed '/./,$!d')"

if [[ $remove -eq 1 ]]; then
    printf '%s\n' "$rest" | sed '/./,$!d' >"$config"
    echo "Removed the $repo patch block from $config"
    exit 0
fi

root="$("$here/upstream-root.sh" "$repo")"
# name<TAB>crate dir of every publishable package in the upstream workspace.
crates="$(cargo metadata --no-deps --offline --format-version 1 --manifest-path "$root/Cargo.toml" |
    jq -r '.packages[] | select(.publish != []) | "\(.name)\t\(.manifest_path | sub("/Cargo.toml$"; ""))"')"

if [[ $# -gt 0 ]]; then
    wanted="$*"
else
    # Every upstream crate a committed lock resolves from crates.io, or already
    # resolves from a patch. Git-pinned crates bypass the proxy and are skipped.
    used="$(while IFS= read -r lock; do lock_packages "$lock"; done < <(consumer_locks) |
        awk '$3 == "-" || $3 ~ /^registry\+/ {print $1}' | sort -u)"
    wanted="$(grep -Fxf <(cut -f1 <<<"$crates") <<<"$used" | tr '\n' ' ' || true)"
fi
[[ -n "${wanted// /}" ]] || die "no $repo crates found in the committed Cargo.lock files; name them explicitly"

{
    echo "$marker (written by trestle/scripts/crates-proxy/patch.sh; never commit)"
    for name in $wanted; do
        dir="$(awk -F'\t' -v n="$name" '$1 == n {print $2}' <<<"$crates")"
        [[ -n "$dir" ]] || die "$name is not a published crate of $repo ($root)"
        echo "patch.crates-io.$name = { path = \"$dir\" }"
    done
    echo "$end"
    # Dotted keys must precede any [table] header, so the blocks go first.
    [[ -z "$rest" ]] || printf '\n%s\n' "$rest"
} >"$config.tmp"
mv "$config.tmp" "$config"

echo "Patched from $root:"
for name in $wanted; do echo "  $name"; done
echo "Before committing, run lock-registry.sh to restore the registry lock entries."
